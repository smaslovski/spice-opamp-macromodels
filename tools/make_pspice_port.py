"""Generate the PSpice versions of the models from the ngspice/LTspice libraries.

    python3 tools/make_pspice_port.py      # writes models/pspice/*.lib

PSpice has no B sources and no C-style ?: operator. The script
  - turns the B sources into E/G ... VALUE={...};
  - writes linear E/G/H sources whose gain is a parameter expression in the
    VALUE form (PSpice 9 accepts only numbers as linear gains);
  - rewrites  {a ? b : c}  as  {IF(a, b, c)}.
Every rule must match exactly once; the script stops otherwise, so a change in
the main libraries cannot silently produce a wrong port.
"""
import os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
SRC = os.path.join(ROOT, 'models')
DST = os.path.join(ROOT, 'models', 'pspice')

AFFINE = {}   # affine B sources are converted like the others (see notes)

HEADER_SUB = [
    ('macromodel (ngspice, LTspice)', 'macromodel (PSpice port)'),
    ('gain and noise is negligible. PSpice/HSPICE need a port (no B sources).',
     'gain and noise is negligible. This file is the PSpice port.'),
]
NOTE = """* PSpice port, generated by tools/make_pspice_port.py from ../{name}.
* Do not edit by hand: change the main library and run the script again.
* Same pins, parameters and behaviour as the main library (checked against
* ngspice with tests/cross_sim.py). Tested with PSpice 9.1 (1999 evaluation
* version), so it should also run in later PSpice releases. Differences:
*   - B sources and parameter-gain E/G/H sources are E/G VALUE={{}} sources;
*     ?: is IF().
*   - VCMN defaults to 1e30, which means mid-supply (PSpice 9 cannot default a
*     parameter to an expression of other parameters).
*   - PSpice differentiates VALUE expressions numerically. To keep the small-
*     signal results exact, the output-stage command current is carried in mA
*     (nicmd...), the crossover input in mV (nvx...), and the clamp excesses on
*     their own nodes (nex...). 1e15 ohm partners give the 1k noise references
*     the two connections PSpice requires.
"""


def wrap(line, width=100):
    """split a long line at operators into + continuation lines (PSpice 9: 132 chars max)"""
    out = []
    while len(line) > width:
        cut = max((i for i in range(20, width) if line[i] in '+-*,'
                   and not re.search(r'\d[eE]$', line[:i])), default=0)
        if cut < 20:
            sys.exit('cannot wrap: ' + line)
        out.append(line[:cut])
        line = '+ ' + line[cut:]
    return out + [line]


def convert(name):
    src = open(os.path.join(SRC, name)).read().split('\n')
    used = {k: 0 for k in AFFINE}
    out = []
    for line in src:
        key = line.rstrip()
        if key in AFFINE:
            used[key] += 1
            if AFFINE[key] is not None:
                out.extend(AFFINE[key].split('\n'))
            continue
        m = re.match(r'^(B)(\w+)\s+(\w+)\s+(\w+)\s+([VI])\s*=\s*(.*)$', line)
        if m:
            _, nm, a, b, kind, expr = m.groups()
            expr = re.sub(r'\{(\w+)\}', r'\1', expr)           # {PARAM} -> PARAM
            expr = re.sub(r'\{([^{}]*)\}', r'(\1)', expr)      # {expr} -> (expr)
            out.extend(wrap(f'{"E" if kind == "V" else "G"}{nm} {a} {b} VALUE={{{expr}}}'))
            continue
        m = re.match(r'^([EG]\w+)\s+(\w+)\s+(\w+)\s+(\w+)\s+(\w+)\s+\{(.+)\}\s*$', line)
        if m:     # PSpice 9 accepts no parameter expression as a linear gain
            nm, a, b, c, d, g = m.groups()
            v = f'V({c})' if d == '0' else f'V({c},{d})'
            out.extend(wrap(f'{nm} {a} {b} VALUE={{({g})*{v}}}'))
            continue
        m = re.match(r'^(H\w+)\s+(\w+)\s+(\w+)\s+(\w+)\s+\{(.+)\}\s*$', line)
        if m:     # CCVS with a parameter gain -> E with I(Vsense)
            nm, a, b, vs, g = m.groups()
            out.extend(wrap(f'E{nm[1:]} {a} {b} VALUE={{({g})*I({vs})}}'))
            continue
        if line.startswith('B'):
            sys.exit(f'{name}: unhandled B source: {line}')
        m = re.match(r'^(\.param\s+\w+\s*=\s*)\{(.*?)\s*\?\s*(.*?)\s*:\s*(.*?)\}\s*$', line)
        if m:
            line = f'{m.group(1)}{{IF({m.group(2)}, {m.group(3)}, {m.group(4)})}}'
        out.append(line)
    txt = '\n'.join(out)
    # PSpice 9 differentiates VALUE expressions numerically (step ~1e-6 absolute).
    # The output-stage split sqrt(i^2+1e-12) bends over ~1 uA, so the command
    # current is carried in mA here (node voltage = 1e3*i): same function, 1000x
    # wider bend, exact small-signal output resistance near zero load current.
    # Clamps: max(V(a)-V(b),0) has a kink that the numerical derivative straddles
    # when a and b are at volts. The excess is formed on its own linear node, so
    # the derivative step is small near the kink (bias-point convergence).
    count = [0]

    def clamp(m):
        f, expr = m.group(1), m.group(2)
        nd = f'nex{count[0]}'
        cl_lines.append(f'Eex{count[0]} {nd} 0 VALUE={{{expr}}}')
        count[0] += 1
        return f'{f}(V({nd}),0)'
    lines = txt.split('\n')
    n_cl = 0
    for k, ln in enumerate(lines):
        if re.match(r'^G\w*clp ', ln):
            cl_lines = []
            body = re.sub(r'(max|min)\((V\(\w+\)[+-]V\(\w+\)),0\)', clamp, ln)
            lines[k] = '\n'.join(cl_lines + [body])
            n_cl += 1
    if n_cl == 0:
        sys.exit(f'{name}: no clamp found')
    txt = '\n'.join(lines)
    # The crossover term tanh(vx/VXO) bends over ~2 mV, but the numerical step is
    # relative to the size of each node voltage (volts at n3/out). So vx is formed
    # first by a linear source, in mV, on its own node (nvx...).
    n_cmd = n_split = 0
    lines = txt.split('\n')
    for k, ln in enumerate(list(lines)):
        if re.match(r'^Eic\w* \w+ 0 VALUE=\{', ln):
            full = ln + (lines[k + 1][1:] if lines[k + 1].startswith('+') else '')
            m = re.search(r'\(V\((\w+)\)-V\((\w+)\)\)', full)
            vx = 'nvx' + ln.split()[0][3:]
            full = full.replace(m.group(0), f'(1e-3*V({vx}))')
            full = full.replace('VALUE={', 'VALUE={1e3*', 1)
            new = [f'E{vx[1:]} {vx} 0 VALUE={{1e3*(V({m.group(1)})-V({m.group(2)}))}}   ; vx in mV'] + wrap(full)
            lines[k] = '\n'.join(new)
            if lines[k + 1].startswith('+'):
                lines[k + 1] = None
            n_cmd += 1
        elif re.match(r'^Gs\w+ \w+ \w+ VALUE=\{0\.5\*\(', ln) and '+1e-12' in ln:
            lines[k] = ln.replace('VALUE={0.5*(', 'VALUE={0.5e-3*(').replace('+1e-12', '+1e-6')
            n_split += 1
    if n_cmd == 0 or n_split != 2 * n_cmd:
        sys.exit(f'{name}: output-stage rescaling failed ({n_cmd}, {n_split})')
    txt = '\n'.join(l for l in lines if l is not None)
    # PSpice: every node needs two connections; a node read only inside VALUE={}
    # has one. The 1e15 ohm partners change the 1 kohm noise by ~1e-12.
    for r in ('Rnv  nnv 0 1e3', 'Rnp  nnp 0 1e3', 'Rnn  nnn 0 1e3'):
        if txt.count(r) != 1:
            sys.exit(f'{name}: missing {r}')
        nm, nd = r.split()[0], r.split()[1]
        txt = txt.replace(r, f'{r}\n{nm}2 {nd} 0 1e15   ; PSpice: second connection at {nd}')
    # PSpice 9: a PARAMS: default cannot refer to other parameters. VCMN = 1e30
    # (the default) means mid-supply, computed inside the subcircuit as VCMX.
    n = txt.count('+ VCMN={0.5*(VCCN+VEEN)}')
    txt = txt.replace('+ VCMN={0.5*(VCCN+VEEN)}', '+ VCMN=1e30')
    txt, k = re.subn(r'(\.param PI2=6\.283185307\n)',
                     r'\1.param VCMX={IF(VCMN>1e29, 0.5*(VCCN+VEEN), VCMN)}   ; VCMN=1e30: mid-supply\n', txt)
    txt, j = re.subn(r'(Ecm ncm0 0 VALUE=\{0\.5\*\(V\(inp\)\+V\(inn\)\))-VCMN\}', r'\1-VCMX}', txt)
    if not (n >= 1 and k == n - (1 if 'FDOPAMP_FULL' in txt else 0) and j == 1):
        sys.exit(f'{name}: VCMN rewrite failed ({n}, {k}, {j})')
    for a, b in HEADER_SUB:
        if a not in txt:
            sys.exit(f'{name}: header text not found: {a}')
        txt = txt.replace(a, b)
    # insert the generated-file note after the version line
    txt = re.sub(r'(\* Version [^\n]*\n)', lambda m: m.group(1) + NOTE.format(name=name), txt, count=1)
    for ln in txt.split('\n'):
        if len(ln) > 132:
            sys.exit(f'{name}: line longer than 132 characters: {ln}')
    for bad in ('?', 'V = ', 'I = '):
        for ln in txt.split('\n'):
            if not ln.startswith('*') and bad in ln:
                sys.exit(f'{name}: leftover "{bad}" in: {ln}')
    return txt


def main():
    os.makedirs(DST, exist_ok=True)
    for name in ('opamp_full.lib', 'fdopamp_full.lib'):
        txt = convert(name)
        open(os.path.join(DST, name), 'w', newline='\r\n').write(txt)
        print('wrote', os.path.relpath(os.path.join(DST, name), ROOT))


if __name__ == '__main__':
    main()
