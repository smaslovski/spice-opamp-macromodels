#!/usr/bin/env python3
"""CMRR / PSRR rules of OPAMP_FULL and FDOPAMP_FULL (model version 1.6).

One source for two uses:
  * the .param block in the libraries (between the markers
    '* ---- begin rejection rules' / '* ---- end rejection rules'), written by
        python3 tools/rejection.py --update
  * the effective rejection of a parameter set, as the model computes it:
        python3 tools/rejection.py CMRR=100k PSRRP=50k PSRRN=20k FPSRRN=300
    (prints the DC values and HF slopes of all four quantities, which ones were
    used as given, which were derived, and conflicts).

Physics. A model without a ground node responds only to differences of its pin
voltages. Then the input-referred errors per volt (output free, measured as
out/A) of the positive supply (P), the negative supply (N) and the input
common mode (C) satisfy, at every frequency,
        T_P(s) + T_N(s) + T_C(s) = 1/A(s) ~ 1/A0 + s/(2*pi*GBW).
The symmetric PSRR (both supplies moved apart by the same amount, per volt of
each supply) is T_S = T_P - T_N. Each T is modelled as t0 + t1*s, and the
identity holds separately for t0 (with g0 = 1/A0) and t1 (g1 = 1/(2*pi*GBW)).
So two of {P, N, C, S} determine the others, up to signs.

Rules (for t0 and t1 separately):
  * given quantities: DC - the ratio parameter is > 0 (CMRR, PSRR, PSRRP,
    PSRRN); HF - also its corner is > 0 (FCMRR; FPSRR for PSRR; FPSRRP or
    else FPSRR for PSRRP; FPSRRN or else FPSRR for PSRRN).
  * the first two given in the order PSRRP, PSRRN, CMRR, PSRR are used
    exactly; the others are derived. DC: with fewer than two given, the
    defaults CMRR = 31.6k, then PSRR = 31.6k are added. HF: with fewer than two
    given, P and then N are added with t1 = KREF*g1 and (1-KREF)*g1 (the
    coupling through the compensation of the gain stage alone).
  * signs: each exact quantity has two signs; of the four combinations the one
    that best matches the remaining given quantities (squared log error) is
    used. With none to match: DC - the one with the largest derived errors
    (conservative: offsets have a random sign from part to part); HF - the one
    with the smallest (the HF coupling is systematic and goes mostly through
    the compensation, which is already included).
"""
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LIBS = [os.path.join(HERE, '..', 'models', n) for n in ('opamp_full.lib', 'fdopamp_full.lib')]
BEGIN = '* ---- begin rejection rules (generated by tools/rejection.py; do not edit) ----'
END = '* ---- end rejection rules ----'


def is0(k):
    return f'(1-min({k},1))'


def is1(k):
    return f'(min({k},1)-min(max({k}-1,0),1))'


def rules(fda=False):
    """(name, SPICE expression) in evaluation order. Inputs: CMRR, PSRR, PSRRP,
    PSRRN, FCMRR, FPSRR, FPSRRP, FPSRRN, A0, GBW, KREF. Outputs: RJP0, RJP1,
    RJN0, RJN1 (coefficients of the explicit coupling of V(vcc)-Vcm and
    V(vee)-Vcm) and TP0..TS1 (the totals).
    fda: FDOPAMP_FULL. Its DM gain node holds a voltage difference, so nothing
    couples through the gain stage: g0 = g1 = 0, the explicit coupling is the
    total, the default PSRR is 10k, and the HF defaults are zeros at
    1e-3*GBW for both supplies (same sign as their DC coupling)."""
    R = []
    p = lambda n, e: R.append((n, e))
    p('RJ2PI', '6.283185307')
    p('RJG0', '0' if fda else '1/A0')
    p('RJG1', '0' if fda else '1/(RJ2PI*GBW)')
    # user flags and magnitudes
    p('RJHP', 'PSRRP>0 ? 1 : 0')
    p('RJHN', 'PSRRN>0 ? 1 : 0')
    p('RJHC', 'CMRR>0 ? 1 : 0')
    p('RJHS', 'PSRR>0 ? 1 : 0')
    p('RJMP0', '1/max(PSRRP,1e-30)')
    p('RJMN0', '1/max(PSRRN,1e-30)')
    p('RJMC0', 'CMRR>0 ? 1/CMRR : 1/31.6k')
    p('RJMS0', 'PSRR>0 ? 1/PSRR : ' + ('1/10k' if fda else '1/31.6k'))
    # DC: defaults to reach two
    p('RJK0', 'RJHP+RJHN+RJHC+RJHS')
    p('RJLA0', 'RJK0<2 ? 1 : 0')
    p('RJGC0', 'max(RJHC,RJLA0)')
    p('RJLB0', 'RJHP+RJHN+RJGC0+RJHS<2 ? 1 : 0')
    p('RJGS0', 'max(RJHS,RJLB0)')
    p('RJGP0', 'RJHP')
    p('RJGN0', 'RJHN')
    for q in 'PNCS':
        p(f'RJU{q}0', f'RJH{q}')          # quantities that can be matched
        p(f'RJF{q}0', '1')                # sign free
        p(f'RJS{q}0', '1')
    solve_order(p, '0')
    # HF corners
    p('RJFPV', 'FPSRRP>0 ? FPSRRP : FPSRR')
    p('RJFNV', 'FPSRRN>0 ? FPSRRN : FPSRR')
    p('RJOP', 'RJFPV>0 ? 1 : 0')
    p('RJON', 'RJFNV>0 ? 1 : 0')
    p('RJOC', 'FCMRR>0 ? 1 : 0')
    p('RJOS', 'FPSRR>0 ? 1 : 0')
    p('RJJP', 'RJHP*RJOP')
    p('RJJN', 'RJHN*RJON')
    p('RJJC', 'RJHC*RJOC')
    p('RJJS', 'RJHS*RJOS')
    fillp = 'abs(TP0)/(RJ2PI*1e-3*GBW)' if fda else 'KREF*RJG1'
    filln = 'abs(TN0)/(RJ2PI*1e-3*GBW)' if fda else '(1-KREF)*RJG1'
    p('RJMP1', f'RJJP>0 ? RJMP0/(RJ2PI*max(RJFPV,1e-30)) : {fillp}')
    p('RJMN1', f'RJJN>0 ? RJMN0/(RJ2PI*max(RJFNV,1e-30)) : {filln}')
    p('RJMC1', 'RJJC>0 ? RJMC0/(RJ2PI*max(FCMRR,1e-30)) : 0')
    p('RJMS1', 'RJJS>0 ? RJMS0/(RJ2PI*max(FPSRR,1e-30)) : 0')
    p('RJK1', 'RJJP+RJJN+RJJC+RJJS')
    p('RJLA1', 'RJK1<2 ? 1-RJJP : 0')
    p('RJGP1', 'max(RJJP,RJLA1)')
    p('RJLB1', 'RJK1+RJLA1<2 ? 1-RJJN : 0')
    p('RJGN1', 'max(RJJN,RJLB1)')
    p('RJGC1', 'RJJC')
    p('RJGS1', 'RJJS')
    for q in 'PNCS':
        p(f'RJU{q}1', f'RJJ{q}')
    p('RJFP1', 'RJJP')
    p('RJFN1', 'RJJN')
    p('RJFC1', '1')
    p('RJFS1', '1')
    # fixed signs of the filled-in slopes. FDA: the default HF coupling keeps the
    # sign of the DC coupling (zero at 1e-3*GBW). (Each name is defined once:
    # LTspice and PSpice reject a repeated .param.)
    p('RJSP1', 'TP0>=0 ? 1 : -1' if fda else '1')
    p('RJSN1', 'TN0>=0 ? 1 : -1' if fda else '1')
    p('RJSC1', '1')
    p('RJSS1', '1')
    solve_order(p, '1')
    # explicit coupling: totals minus the part through the gain stage (nref)
    if fda:
        for q in 'PN':
            for o in '01':
                p(f'RJ{q}{o}', f'T{q}{o}')
    else:
        p('RJP0', 'TP0-KREF*RJG0')
        p('RJP1', 'TP1-KREF*RJG1')
        p('RJN0', 'TN0-(1-KREF)*RJG0')
        p('RJN1', 'TN1-(1-KREF)*RJG1')
    return R


def solve_order(p, o):
    """Pair selection and sign choice for one order (0: DC, 1: HF slope)."""
    g = f'RJG{o}'
    tb = '-1' if o == '0' else '1'
    # pair selection: first and second given in the order P, N, C, S
    p(f'RJKN{o}', f'RJGP{o}')
    p(f'RJKC{o}', f'RJGP{o}+RJGN{o}')
    p(f'RJKS{o}', f'RJGP{o}+RJGN{o}+RJGC{o}')
    p(f'RJXP{o}', f'RJGP{o}')
    p(f'RJXN{o}', f'RJGN{o}*{is0(f"RJKN{o}")}')
    p(f'RJXC{o}', f'RJGC{o}*{is0(f"RJKC{o}")}')
    p(f'RJXS{o}', f'RJGS{o}*{is0(f"RJKS{o}")}')
    p(f'RJYP{o}', '0')
    p(f'RJYN{o}', f'RJGN{o}*{is1(f"RJKN{o}")}')
    p(f'RJYC{o}', f'RJGC{o}*{is1(f"RJKC{o}")}')
    p(f'RJYS{o}', f'RJGS{o}*{is1(f"RJKS{o}")}')
    for r in 'XY':
        w = lambda q: f'RJ{r}{q}{o}'
        p(f'RJA{r}{o}', f'{w("P")}+{w("C")}+{w("S")}')
        p(f'RJB{r}{o}', f'{w("N")}+{w("C")}-{w("S")}')
        p(f'RJC{r}{o}', f'{w("C")}*{g}')
        p(f'RJQ{r}{o}', f'1-2*{w("C")}')
        p(f'RJM{r}{o}', '+'.join(f'{w(q)}*RJM{q}{o}' for q in 'PNCS'))
        p(f'RJF{r}{o}', '+'.join(f'{w(q)}*RJF{q}{o}' for q in 'PNCS'))
        p(f'RJS{r}{o}', '+'.join(f'{w(q)}*RJS{q}{o}' for q in 'PNCS'))
    p(f'RJDET{o}', f'RJAX{o}*RJBY{o}-RJAY{o}*RJBX{o}')
    for q in 'PNCS':
        p(f'RJE{q}{o}', f'RJU{q}{o}*(1-RJX{q}{o}-RJY{q}{o})')
    for q in 'PNC':
        p(f'RJD{q}{o}', f'1-RJX{q}{o}-RJY{q}{o}')
    p(f'RJMXY{o}', f'RJMX{o}+RJMY{o}+1e-30')

    def solve(sx, sy, k):
        p(f'RJRX{k}{o}', f'RJCX{o}+RJQX{o}*(RJFX{o}*({sx})+(1-RJFX{o})*RJSX{o})*RJMX{o}')
        p(f'RJRY{k}{o}', f'RJCY{o}+RJQY{o}*(RJFY{o}*({sy})+(1-RJFY{o})*RJSY{o})*RJMY{o}')
        p(f'RJTP{k}{o}', f'(RJRX{k}{o}*RJBY{o}-RJRY{k}{o}*RJBX{o})/RJDET{o}')
        p(f'RJTN{k}{o}', f'(RJAX{o}*RJRY{k}{o}-RJAY{o}*RJRX{k}{o})/RJDET{o}')
        p(f'RJTC{k}{o}', f'{g}-RJTP{k}{o}-RJTN{k}{o}')
        p(f'RJTS{k}{o}', f'RJTP{k}{o}-RJTN{k}{o}')
    for k, (sx, sy) in enumerate(((1, 1), (1, -1), (-1, 1), (-1, -1)), 1):
        solve(sx, sy, k)
        for q in 'PNCS':     # log mismatch of each quantity that can be matched
            p(f'RJL{q}{k}{o}', f'log(max(abs(RJT{q}{k}{o}),1e-30)/max(RJM{q}{o},1e-30))')
        terms = '+'.join(f'RJE{q}{o}*RJL{q}{k}{o}*RJL{q}{k}{o}' for q in 'PNCS')
        tie = '+'.join(f'RJD{q}{o}*abs(RJT{q}{k}{o})' for q in 'PNC')
        p(f'RJMM{k}{o}', terms)
        p(f'RJTI{k}{o}', tie)
        p(f'RJCO{k}{o}', f'RJMM{k}{o}+({tb})*1e-6*RJTI{k}{o}/RJMXY{o}')
    p(f'RJSGX{o}', f'min(RJCO1{o},RJCO2{o})<=min(RJCO3{o},RJCO4{o}) ? 1 : -1')
    p(f'RJSA{o}', f'RJCO1{o}<=RJCO2{o} ? 1 : -1')
    p(f'RJSB{o}', f'RJCO3{o}<=RJCO4{o} ? 1 : -1')
    p(f'RJSGY{o}', f'0.5*(1+RJSGX{o})*RJSA{o}+0.5*(1-RJSGX{o})*RJSB{o}')
    solve(f'RJSGX{o}', f'RJSGY{o}', '')
    p(f'TP{o}', f'RJTP{o}')
    p(f'TN{o}', f'RJTN{o}')
    p(f'TC{o}', f'RJTC{o}')
    p(f'TS{o}', f'RJTS{o}')


def spice_block(fda=False):
    names = [n for n, _ in rules(fda)]
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        sys.exit(f'duplicate rule names: {sorted(dup)}')
    lines = [BEGIN]
    for n, e in rules(fda):
        lines.append(f'.param {n}={{{e}}}')
    lines.append(END)
    return '\n'.join(lines)


# ---- Python evaluation of the same rules ----------------------------------------
SUF = {'f': 1e-15, 'p': 1e-12, 'n': 1e-9, 'u': 1e-6, 'm': 1e-3, 'k': 1e3, 'meg': 1e6, 'g': 1e9, 't': 1e12}


def num(s):
    s = str(s).strip()
    m = re.match(r'^([-+]?[0-9.]+(?:[eE][-+]?\d+)?)([a-zA-Z]*)$', s)
    if not m:
        return float(s)
    v, u = float(m.group(1)), m.group(2).lower()
    if u.startswith('meg'):
        return v * 1e6
    return v * SUF.get(u[:1], 1) if u else v


def pyexpr(e):
    e = re.sub(r'(\d)k\b', r'\1e3', e)
    m = re.match(r'^(.*?)\s*\?\s*(.*?)\s*:\s*(.*)$', e)
    if m:
        return f'(({m.group(2)}) if ({m.group(1)}) else ({m.group(3)}))'
    return e


def evaluate(user, fda=False):
    env = dict(CMRR=0, PSRR=0, PSRRP=0, PSRRN=0, FCMRR=0, FPSRR=0, FPSRRP=0, FPSRRN=0,
               A0=100e3 if fda else 200e3, GBW=100e6 if fda else 1e6, KREF=0.5)
    env.update({k: num(v) for k, v in user.items()})
    ns = dict(min=min, max=max, abs=abs, log=lambda x: math.log(x))
    for n, e in rules(fda):
        env[n] = eval(pyexpr(e), ns, env)
    return env


def report(user, fda=False):
    v = evaluate(user, fda)
    db = lambda x: f'{-20 * math.log10(abs(x)):6.1f} dB' if abs(x) > 1e-300 else '   inf dB'
    name = dict(P='PSRRP', N='PSRRN', C='CMRR', S='PSRR')
    print(f'{"":6} {"DC error":>11} {"(ratio)":>9} {"HF slope s":>11} {"corner":>10}  role')
    for q in 'PNCS':
        t0, t1 = v[f'T{q}0'], v[f'T{q}1']
        f = abs(t0) / (2 * math.pi * abs(t1)) if t1 else float('inf')
        role = []
        for o, tag in (('0', 'DC'), ('1', 'HF')):
            if v[f'RJX{q}{o}'] or v[f'RJY{q}{o}']:
                role.append(f'{tag} exact')
            elif v[f'RJU{q}{o}']:
                m, t = v[f'RJM{q}{o}'], abs(v[f'T{q}{o}'])
                err = 20 * math.log10(max(t, 1e-300) / m)
                role.append(f'{tag} derived, {err:+.1f} dB from the given value' + (' (CONFLICT)' if abs(err) > 1 else ''))
            else:
                role.append(f'{tag} derived')
        print(f'{name[q]:6} {t0:+11.3e} {db(t0)} {t1:+11.3e} {f:10.4g}  ' + '; '.join(role))


def update():
    for lib in LIBS:
        blk = spice_block('fdopamp' in lib)
        txt = open(lib).read()
        if BEGIN not in txt:
            print(f'{lib}: no marker, skipped')
            continue
        a = txt.index(BEGIN)
        b = txt.index(END) + len(END)
        txt = txt[:a] + blk + txt[b:]
        open(lib, 'w').write(txt)
        print(f'{lib}: rules updated ({len(rules("fdopamp" in lib))} params)')


if __name__ == '__main__':
    if sys.argv[1:] == ['--update']:
        update()
    elif sys.argv[1:] == ['--print']:
        print(spice_block())
    else:
        args = sys.argv[1:]
        fda = '--fda' in args
        report(dict(a.split('=', 1) for a in args if a != '--fda'), fda)
