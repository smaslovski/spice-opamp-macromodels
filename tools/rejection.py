#!/usr/bin/env python3
"""CMRR / PSRR rules of OPAMP_FULL and FDOPAMP_FULL (model version 1.7).

One source for two uses:
  * the .param block in the libraries (between the markers
    '* ---- begin rejection rules' / '* ---- end rejection rules'), written by
        python3 tools/rejection.py --update
  * the effective rejection of a parameter set, as the model computes it:
        python3 tools/rejection.py CMRR=100k PSRRP=50k PSRRN=-20k FPSRRN=300
    (prints the DC values and HF slopes of all four quantities, which ones were
    used as given, which were derived, and conflicts).

Physics. A model without a ground node responds only to differences of its pin
voltages. Then the input-referred errors per volt (output free, measured as
out/A) of the positive supply (P), the negative supply (N) and the input
common mode (C) satisfy, at every frequency,
        T_P(s) + T_N(s) + T_C(s) = 1/A(s) ~ 1/A0 + s/(2*pi*GBW).
The symmetric PSRR (both supplies moved apart by the same amount, per volt of
each supply) is T_S = T_P - T_N. Each T is modelled as t0 + t1*s, and the
identity holds separately for t0 (with g0 = 1/A0) and t1 (g1 = 1/(2*pi*GBW)).
So two of {P, N, C, S} determine the others.

Signs. A positive T moves the output like a positive voltage at the + input
(the polarity of VOS) when its pin (or the input common mode) rises.
  * DC: the DC errors come mostly from device mismatch, so their signs differ
    from unit to unit (and can change with temperature). PSRRP, PSRRN, CMRR and
    PSRR are therefore signed: t0 = 1/value. 0 means not given.
  * HF (OPAMP): the slopes come from the coupling of a supply through the
    compensation of the gain stage. That is systematic, so the signs are not
    taken from the parameters: the supply slopes are positive, and the sign of
    an exact CMRR or PSRR slope is the one that keeps the derived supply slopes
    positive (if both do, the one giving the smaller derived slopes; for an
    exact pair CMRR + PSRR the PSRR sign follows KREF: + if KREF >= 0.5).
  * HF (FDA): the differential output has no systematic coupling (g1 = 0), so
    the HF coupling is again mismatch: each slope takes the sign of its DC
    value (a zero at the corner frequency).

Rules (for t0 and t1 separately):
  * given quantities: DC - the value is not 0; HF - also its corner is > 0
    (FCMRR; FPSRR for PSRR; FPSRRP or else FPSRR for PSRRP; FPSRRN or else
    FPSRR for PSRRN).
  * the first two given in the order PSRRP, PSRRN, CMRR, PSRR are used
    exactly; the others are derived. DC: with fewer than two given (e.g. CMRR
    or PSRR set to 0), CMRR, then PSRR are added with the default values
    (OPAMP -31.6k, 31.6k; FDA 31.6k, 10k). HF: with fewer than two given, P and
    then N are added with t1 = KREF*g1 and (1-KREF)*g1 (OPAMP; the coupling
    through the compensation of the gain stage alone) or with a zero at
    1e-3*GBW (FDA).
"""
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LIBS = [os.path.join(HERE, '..', 'models', n) for n in ('opamp_full.lib', 'fdopamp_full.lib')]
BEGIN = '* ---- begin rejection rules (generated by tools/rejection.py; do not edit) ----'
END = '* ---- end rejection rules ----'
# parameter defaults as in the subcircuit lines (Python evaluation and report)
DEFAULTS = {False: dict(CMRR=-31.6e3, PSRR=31.6e3, A0=200e3, GBW=1e6),
            True: dict(CMRR=31.6e3, PSRR=10e3, A0=100e3, GBW=100e6)}


def is1(k):
    """1 if k == 1, 0 if k == 0 or k >= 2 (k a non-negative integer)"""
    return f'(min({k},1)-min(max({k}-1,0),1))'


def rules(fda=False):
    """(name, SPICE expression) in evaluation order. Inputs: CMRR, PSRR, PSRRP,
    PSRRN, FCMRR, FPSRR, FPSRRP, FPSRRN, A0, GBW, KREF. Outputs: RJP0, RJP1,
    RJN0, RJN1 (coefficients of the explicit coupling of V(vcc)-Vcm and
    V(vee)-Vcm) and TP0..TS1 (the totals)."""
    R = []
    p = lambda n, e: R.append((n, e))
    p('RJ2PI', '6.283185307')
    p('RJG0', '0' if fda else '1/A0')
    p('RJG1', '0' if fda else '1/(RJ2PI*GBW)')
    dc, ds = ('1/31.6k', '1/10k') if fda else ('-1/31.6k', '1/31.6k')
    # DC: signed errors of the given values
    for q, v in (('P', 'PSRRP'), ('N', 'PSRRN'), ('C', 'CMRR'), ('S', 'PSRR')):
        p(f'RJH{q}', f'abs({v})>0 ? 1 : 0')
    # (written without a division by a zero value in either case)
    p('RJVP0', 'RJHP/(PSRRP+1-RJHP)')
    p('RJVN0', 'RJHN/(PSRRN+1-RJHN)')
    p('RJVC0', f'RJHC/(CMRR+1-RJHC)+(1-RJHC)*({dc})')
    p('RJVS0', f'RJHS/(PSRR+1-RJHS)+(1-RJHS)*({ds})')
    p('RJGC0', 'RJHP+RJHN+RJHC+RJHS<2 ? 1 : RJHC')
    p('RJGS0', 'RJHP+RJHN+RJGC0+RJHS<2 ? 1 : RJHS')
    select(p, '0', 'RJHP', 'RJHN', 'RJGC0', 'RJGS0')
    solve(p, '0', 'RJVP0', 'RJVN0', 'RJVC0', 'RJVS0')
    # HF: given slopes
    p('RJFPV', 'FPSRRP>0 ? FPSRRP : FPSRR')
    p('RJFNV', 'FPSRRN>0 ? FPSRRN : FPSRR')
    p('RJJP', 'RJFPV>0 ? RJHP : 0')
    p('RJJN', 'RJFNV>0 ? RJHN : 0')
    p('RJJC', 'FCMRR>0 ? RJHC : 0')
    p('RJJS', 'FPSRR>0 ? RJHS : 0')
    p('RJLA1', 'RJJP+RJJN+RJJC+RJJS<2 ? 1-RJJP : 0')
    p('RJGP1', 'max(RJJP,RJLA1)')
    p('RJGN1', 'RJJP+RJJN+RJJC+RJJS+RJLA1<2 ? 1 : RJJN')
    select(p, '1', 'RJGP1', 'RJGN1', 'RJJC', 'RJJS')
    if fda:
        # mismatch: each slope has the sign of its DC value (zero at the corner)
        p('RJVP1', 'RJJP>0 ? RJVP0/(RJ2PI*max(RJFPV,1e-30)) : TP0/(RJ2PI*1e-3*GBW)')
        p('RJVN1', 'RJJN>0 ? RJVN0/(RJ2PI*max(RJFNV,1e-30)) : TN0/(RJ2PI*1e-3*GBW)')
        p('RJVC1', 'RJJC>0 ? RJVC0/(RJ2PI*max(FCMRR,1e-30)) : 0')
        p('RJVS1', 'RJJS>0 ? RJVS0/(RJ2PI*max(FPSRR,1e-30)) : 0')
    else:
        # systematic: supply slopes positive, CMRR/PSRR signs chosen (see above)
        p('RJVP1', 'RJJP>0 ? abs(RJVP0)/(RJ2PI*max(RJFPV,1e-30)) : KREF*RJG1')
        p('RJVN1', 'RJJN>0 ? abs(RJVN0)/(RJ2PI*max(RJFNV,1e-30)) : (1-KREF)*RJG1')
        p('RJMC1', 'RJJC>0 ? abs(RJVC0)/(RJ2PI*max(FCMRR,1e-30)) : 0')
        p('RJMS1', 'RJJS>0 ? abs(RJVS0)/(RJ2PI*max(FPSRR,1e-30)) : 0')
        p('RJUC1', 'RJG1-RJXP1*RJVP1-RJXN1*RJVN1-RJYS1*RJMS1-RJMC1')
        p('RJSC1', 'RJUC1>=0 ? 1 : -1')
        p('RJVC1', 'RJSC1*RJMC1')
        p('RJSSP', 'RJVP1>=RJMS1 ? 1 : -1')
        p('RJSSN', 'RJVN1>=RJMS1 ? -1 : 1')
        p('RJSSK', 'KREF>=0.5 ? 1 : -1')
        p('RJVS1', 'RJMS1*(RJXP1*RJSSP+RJXN1*RJSSN+RJXC1*RJSSK)')
    solve(p, '1', 'RJVP1', 'RJVN1', 'RJVC1', 'RJVS1')
    # explicit coupling: totals minus the part through the gain stage (nref)
    if fda:
        for q in 'PN':
            for o in '01':
                p(f'RJ{q}{o}', f'T{q}{o}')
    else:
        p('RJP0', 'TP0-KREF*RJG0')
        p('RJP1', 'TP1-KREF*RJG1')
        p('RJN0', 'TN0-(1-KREF)*RJG0')
        p('RJN1', 'TN1-(1-KREF)*RJG1')
    return R


def select(p, o, gp, gn, gc, gs):
    """X = first and Y = second given in the order P, N, C, S. There are always
    at least two given, so X is never S and Y is never P."""
    p(f'RJXP{o}', gp)
    p(f'RJXN{o}', f'{gp}>0 ? 0 : {gn}')
    p(f'RJXC{o}', f'{gp}+{gn}>0 ? 0 : {gc}')
    p(f'RJYN{o}', f'{gp}>0 ? {gn} : 0')
    p(f'RJYC{o}', f'{gc}*{is1(f"{gp}+{gn}")}')
    p(f'RJYS{o}', f'{gs}*{is1(f"{gp}+{gn}+{gc}")}')


def solve(p, o, vp, vn, vc, vs):
    """Solve a*TP + b*TN = r for the exact pair X, Y. Constraints:
    P: TP = vp   N: TN = vn   C: TP + TN = g - vc   S: TP - TN = vs"""
    g = f'RJG{o}'
    p(f'RJAX{o}', f'RJXP{o}+RJXC{o}')
    p(f'RJBX{o}', f'RJXN{o}+RJXC{o}')
    p(f'RJRX{o}', f'RJXP{o}*{vp}+RJXN{o}*{vn}+RJXC{o}*({g}-{vc})')
    p(f'RJAY{o}', f'RJYC{o}+RJYS{o}')
    p(f'RJBY{o}', f'RJYN{o}+RJYC{o}-RJYS{o}')
    p(f'RJRY{o}', f'RJYN{o}*{vn}+RJYC{o}*({g}-{vc})+RJYS{o}*{vs}')
    p(f'RJD{o}', f'RJAX{o}*RJBY{o}-RJAY{o}*RJBX{o}')
    p(f'TP{o}', f'(RJRX{o}*RJBY{o}-RJRY{o}*RJBX{o})/RJD{o}')
    p(f'TN{o}', f'(RJAX{o}*RJRY{o}-RJAY{o}*RJRX{o})/RJD{o}')
    p(f'TC{o}', f'{g}-TP{o}-TN{o}')
    p(f'TS{o}', f'TP{o}-TN{o}')


def spice_block(fda=False):
    R = rules(fda)
    names = [n for n, _ in R]
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        sys.exit(f'duplicate rule names: {sorted(dup)}')
    lines = [BEGIN] + [f'.param {n}={{{e}}}' for n, e in R] + [END]
    long = [l for l in lines if len(l) > 132]
    if long:
        sys.exit(f'lines over 132 characters: {long}')
    return '\n'.join(lines)


# ---- Python evaluation of the same rules ----------------------------------------
SUF = {'f': 1e-15, 'p': 1e-12, 'n': 1e-9, 'u': 1e-6, 'm': 1e-3, 'k': 1e3, 'meg': 1e6, 'g': 1e9, 't': 1e12}


def num(s):
    s = str(s).strip()
    m = re.match(r'^([-+]?[0-9.]+(?:[eE][-+]?\d+)?)([a-zA-Z]*)$', s)
    if not m:
        return float(s)
    v, u = float(m.group(1)), m.group(2).lower()
    if u.startswith('meg'):
        return v * 1e6
    return v * SUF.get(u[:1], 1) if u else v


def pyexpr(e):
    e = re.sub(r'(\d)k\b', r'\1e3', e)
    m = re.match(r'^(.*?)\s*\?\s*(.*?)\s*:\s*(.*)$', e)
    if m:
        return f'(({m.group(2)}) if ({m.group(1)}) else ({m.group(3)}))'
    return e


def evaluate(user, fda=False):
    env = dict(PSRRP=0, PSRRN=0, FCMRR=0, FPSRR=0, FPSRRP=0, FPSRRN=0, KREF=0.5)
    env.update(DEFAULTS[fda])
    env.update({k: num(v) for k, v in user.items()})
    ns = dict(min=min, max=max, abs=abs)
    for n, e in rules(fda):
        env[n] = eval(pyexpr(e), ns, env)
    return env


def report(user, fda=False):
    """DC values and HF slopes of the four quantities, and how each was used.
    given: set in user; default: the subcircuit default of CMRR or PSRR."""
    v = evaluate(user, fda)
    user = {k.upper(): x for k, x in user.items()}
    rdb = lambda x: f'{-20 * math.log10(abs(x)):6.1f} dB' if abs(x) > 1e-300 else '   inf dB'
    name = dict(P='PSRRP', N='PSRRN', C='CMRR', S='PSRR')
    corner = dict(P=('FPSRRP', 'FPSRR'), N=('FPSRRN', 'FPSRR'), C=('FCMRR',), S=('FPSRR',))
    print(f'{"":6} {"value":>11} {"DC error":>11} {"":>9} {"HF slope s":>11} {"corner Hz":>10}  role')
    for q in 'PNCS':
        t0, t1 = v[f'T{q}0'], v[f'T{q}1']
        f = abs(t0) / (2 * math.pi * abs(t1)) if t1 else float('inf')
        val = 1 / t0 if t0 else float('inf')
        src = 'given' if name[q] in user else ('default' if name[q] in DEFAULTS[fda] else '')
        role = []
        for o, tag in (('0', 'DC'), ('1', 'HF')):
            exact = (v.get(f'RJX{q}{o}', 0) or v.get(f'RJY{q}{o}', 0))
            if exact:
                role.append(f'{tag} exact')
                continue
            given = src == 'given' and (o == '0' or any(num(user.get(c, 0)) > 0 for c in corner[q]))
            if given:
                if o == '0':
                    want = 1 / num(user[name[q]])
                else:
                    fc = next(num(user[c]) for c in corner[q] if num(user.get(c, 0)) > 0)
                    want = abs(1 / num(user[name[q]])) / (2 * math.pi * fc)
                got = abs(v[f'T{q}{o}'])
                err = 20 * math.log10(max(got, 1e-300) / abs(want))
                sgn = '' if o == '1' or got == 0 or (v[f'T{q}{o}'] > 0) == (want > 0) else ', opposite sign'
                bad = abs(err) > 1 or sgn
                role.append(f'{tag} derived, {err:+.1f} dB from the given value{sgn}' + (' (CONFLICT)' if bad else ''))
            else:
                neg = (not fda and o == '1' and q in 'PN' and v[f'T{q}1'] < 0)
                role.append(f'{tag} derived' + (' (negative: the given slopes exceed 1/(2*pi*GBW))' if neg else ''))
        print(f'{name[q]:6} {val:+11.4g} {t0:+11.3e} {rdb(t0)} {t1:+11.3e} {f:10.4g}  '
              + (f'{src}: ' if src else '') + '; '.join(role))


def update():
    for lib in LIBS:
        blk = spice_block('fdopamp' in lib)
        txt = open(lib).read()
        if BEGIN not in txt:
            print(f'{lib}: no marker, skipped')
            continue
        a = txt.index(BEGIN)
        b = txt.index(END) + len(END)
        txt = txt[:a] + blk + txt[b:]
        open(lib, 'w').write(txt)
        print(f'{lib}: rules updated ({len(rules("fdopamp" in lib))} params)')


if __name__ == '__main__':
    if sys.argv[1:] == ['--update']:
        update()
    elif sys.argv[1:] == ['--print']:
        print(spice_block())
    else:
        args = sys.argv[1:]
        fda = '--fda' in args
        report(dict(a.split('=', 1) for a in args if a != '--fda'), fda)
